import test from 'node:test'
import assert from 'node:assert/strict'
import { validatePlantUpdateRequest } from '../functions/api/manager/plant-update-request-lib.mjs'

const validRequest = () => ({
  idempotencyKey: 'd3c98287-368b-4d51-9f99-f8e01f9564f1',
  expectedRevision: 'sanity-revision-123',
  product: { name: 'Cycas', categoryIds: ['category-123'] },
})

test('plant update request accepts the Manager PATCH contract and standard browser UUID', () => {
  assert.deepEqual(validatePlantUpdateRequest(validRequest()), [])
})

test('plant update request reports malformed JSON body without exposing values', () => {
  assert.deepEqual(validatePlantUpdateRequest(null), ['body'])
  assert.deepEqual(validatePlantUpdateRequest([]), ['body'])
})

test('plant update request identifies invalid contract fields independently', () => {
  assert.deepEqual(validatePlantUpdateRequest({
    idempotencyKey: 'not-a-uuid',
    expectedRevision: '',
    product: [],
  }), ['idempotencyKey', 'product', 'expectedRevision'])
})

test('plant update request accepts a UUID v4 generated by crypto.randomUUID', () => {
  assert.deepEqual(validatePlantUpdateRequest({
    idempotencyKey: '22affdac-8b2f-42d6-bd12-2094090f0488',
    expectedRevision: 'revision',
    product: {},
  }), [])
})
